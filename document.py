    add_paragraph(
        "اتفق الطرفان على أن يقوم الطرف الثاني بسداد دفعة مقدمة من إجمالي ثمن البيع بموجب شيك يُسَلَّم إلى الطرف الأول عند توقيع هذا الاتفاق، وتكون بياناته كما يلي:")
    add_paragraph(
        "اسم البنك: ..........................................................................................")
    add_paragraph(
        "رقم الشيك: ............................................ تاريخ الشيك: ............................................")
