from docx import Document
from docx.shared import Pt, Inches, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn


def create_contract():
    doc = Document()

    # Set RTL (Right-to-Left) for the document
    def set_rtl(paragraph):
        pPr = paragraph._p.get_or_add_pPr()
        bidi = pPr.makeelement(qn('w:bidi'), {})
        pPr.append(bidi)
        paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT

    # Set standard font (Traditional Arabic or Arial)
    style = doc.styles['Normal']
    style.font.name = 'Arial'
    style.font.size = Pt(14)
    style.element.rPr.rFonts.set(qn('w:eastAsia'), 'Arial')

    def add_paragraph(text, bold=False, underline=False, size=14, align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=12):
        p = doc.add_paragraph()
        p.alignment = align
        set_rtl(p)
        run = p.add_run(text)
        run.bold = bold
        run.underline = underline
        run.font.size = Pt(size)
        p.paragraph_format.space_after = Pt(space_after)
        return p

    # Title (Centered and Bold)
    add_paragraph("اتفاق ابتدائي لبيع عقار", bold=True, size=18, align=WD_ALIGN_PARAGRAPH.CENTER, space_after=24)

    # Intro
    add_paragraph("إنه في يوم .................... الموافق ....../....../...... تحرر هذا الاتفاق بين كل من:")

    # Party 1
    add_paragraph("أولاً: الطرف الأول (البائع)", bold=True)
    add_paragraph("السيد/ ................................................................")
    add_paragraph(
        "الجنسية: ............................................................... رقم بطاقة الرقم القومي: ...............................................................")
    add_paragraph("العنوان: ................................................................")
    add_paragraph("(ويُشار إليه فيما بعد بـ \"الطرف الأول\" أو \"البائع\")")

    # Party 2
    add_paragraph("ثانياً: الطرف الثاني (المشتري)", bold=True)
    add_paragraph("السيد/ ................................................................")
    add_paragraph(
        "الجنسية: ............................................................... رقم بطاقة الرقم القومي: ...............................................................")
    add_paragraph("العنوان: ................................................................")
    add_paragraph("(ويُشار إليه فيما بعد بـ \"الطرف الثاني\" أو \"المشتري\")")

    add_paragraph("وبعد أن أقر الطرفان بأهليتهما القانونية للتعاقد والتصرف، فقد اتفقا على ما يلي:")

    # Clause 1
    add_paragraph("البند الأول: موضوع الاتفاق", bold=True, underline=True, space_after=12)
    add_paragraph("باع الطرف الأول إلى الطرف الثاني، القابل لذلك، العقار الكائن في:")
    add_paragraph(
        "........................................................................................................................................................")
    add_paragraph(
        "........................................................................................................................................................")
    add_paragraph("وذلك وفقاً لبيانات الملكية والمستندات الخاصة بالعقار، وبالشروط والأحكام الواردة في هذا الاتفاق.")

    # Clause 2
    add_paragraph("البند الثاني: إجمالي الثمن وصافي المبلغ المستحق للبائع", bold=True, underline=True, space_after=12)
    add_paragraph(
        "اتفق الطرفان على أن يكون صافي ثمن بيع العقار المستحق للطرف الأول (البائع) مبلغاً وقدره 38,000,000 جنيه مصري فقط لا غير (ثمانية وثلاثون مليون جنيه مصري).")
    add_paragraph(
        "ويُعد هذا المبلغ صافي المبلغ المستحق للبائع، ولا يشمل ضريبة التصرفات العقارية أو أي ضرائب أو رسوم أو مصاريف أخرى لازمة لنقل الملكية، والتي يلتزم الطرف الثاني (المشتري) بسدادها بالإضافة إلى هذا المبلغ، وفقاً للبند الرابع من هذا الاتفاق.")

