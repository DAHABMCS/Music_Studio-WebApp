    # Clause 9
    add_paragraph("البند التاسع: أحكام عامة", bold=True, underline=True, space_after=12)
    add_paragraph("1. يُعد هذا الاتفاق ملزماً للطرفين في حدود أحكامه والقانون واجب التطبيق.")
    add_paragraph("2. لا يجوز تعديل أي بند من بنود هذا الاتفاق إلا بموجب ملحق كتابي موقع من الطرفين.")
    add_paragraph(
        "3. في حالة نشوء أي نزاع بشأن تفسير هذا الاتفاق أو تنفيذه، تتم تسويته وفقاً للقوانين المصرية والجهة القضائية المختصة.")
    add_paragraph("4. خُرر هذا الاتفاق من نسختين أصليتين، تسلم كل طرف نسخة للعمل بموجبها.")

    # Clause 10
    add_paragraph("البند العاشر: الشرط الجزائي والتعويض", bold=True, underline=True, space_after=12)
    add_paragraph(
        "أولاً: في حال إخلال الطرف الثاني (المشتري) بأي من التزاماته الجوهرية الواردة في هذا الاتفاق – بما في ذلك على سبيل المثال لا الحصر: عدم تسليم الشيك المصرفي المصدق الخاص بباقي الثمن في يوم التنازل، أو عدم تحصيل أي شيك من الشيكات المذكورة، أو الامتناع عن استكمال إجراءات نقل الملكية دون سبب مشروع – يلتزم الطرف الثاني بأداء شرط جزائي للطرف الأول (البائع) قدره 2,000,000 جنيه مصري (مليونان جنيه مصري فقط لا غير)، وذلك دون الإخلال بحق الطرف الأول في المطالبة بالتعويض عن أي أضرار فعلية تزيد عن هذا المبلغ، ودون الإخلال بحقه في الاحتفاظ بالمبالغ المحصلة فعلياً.")
